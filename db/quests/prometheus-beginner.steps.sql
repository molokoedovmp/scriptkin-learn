`IN` проверяет, совпадает ли значение с одним из перечисленных вариантов:

```sql
WHERE event_type IN (
  'MANUAL_SHUTDOWN',
  'MAIN_BUS_OFFLINE',
  'EMERGENCY_POWER'
)
```

Такую запись удобно использовать вместо нескольких условий, соединённых через `OR`.

`BETWEEN` ограничивает значение диапазоном. Обе границы входят в результат:

```sql
WHERE recorded_at BETWEEN
  TIMESTAMP '2187-09-14 03:19:00'
  AND TIMESTAMP '2187-09-14 03:20:00'
```

Это равнозначно двум сравнениям: `recorded_at >= ...` и `recorded_at <= ...`.

`ORDER BY recorded_at ASC` располагает записи от ранних к поздним. `ASC` используется по умолчанию, поэтому его можно не писать.

