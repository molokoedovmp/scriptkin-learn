`GROUP BY` объединяет строки с одинаковым значением выбранного столбца. Например, запрос:

```sql
SELECT event_type, COUNT(*)
FROM system_events
GROUP BY event_type;
```

создаёт отдельную группу для каждого `event_type`, а `COUNT(*)` считает строки внутри каждой группы.

Вычисленной колонке можно дать понятное имя:

```sql
COUNT(*) AS event_count
```

Фильтрация выполняется до группировки. Поэтому сначала `WHERE` оставляет события нужного сектора и времени, а затем `GROUP BY` распределяет их по типам:

```sql
WHERE sector_id = 6
  AND recorded_at > TIMESTAMP '2187-09-14 03:36:45'
GROUP BY event_type
```

Агрегированный результат тоже можно сортировать:

```sql
ORDER BY event_count DESC
```

