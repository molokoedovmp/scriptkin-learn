`MIN()` возвращает самое маленькое значение выбранного столбца:

```sql
SELECT MIN(oxygen_level)
FROM medical_scans;
```

`MAX()` возвращает самое большое значение:

```sql
SELECT MAX(tissue_anomaly)
FROM medical_scans;
```

Несколько агрегатных функций можно выполнить в одном `SELECT`. Все подходящие строки превратятся в одну итоговую строку:

```sql
SELECT
  MIN(oxygen_level),
  MAX(body_temperature),
  MAX(tissue_anomaly)
FROM medical_scans;
```

Без `WHERE` запрос обработает сканирования всего экипажа. Условие `crew_id = 203` оставляет только записи Jason Miller.

Как и в прошлом уроке, `AS` задаёт понятные названия вычисленным колонкам:

```sql
MIN(oxygen_level) AS min_oxygen
```

