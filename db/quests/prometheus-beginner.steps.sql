`CASE` позволяет проверить условия для каждой строки и вывести вычисленное значение:

```sql
CASE
  WHEN fuel_percent < 20 THEN 'no_fuel'
  ELSE 'ready'
END AS pod_condition
```

Условий `WHEN` может быть несколько. SQL проверяет их сверху вниз и возвращает результат первого подходящего условия, поэтому порядок имеет значение:

```sql
CASE
  WHEN status = 'launched' THEN 'already_launched'
  WHEN fuel_percent < 20 THEN 'no_fuel'
  WHEN hull_integrity < 50 THEN 'hull_damaged'
  WHEN launch_lock = TRUE THEN 'launch_locked'
  ELSE 'ready'
END AS pod_condition
```

`ELSE` используется, если ни одно условие не выполнилось. Выражение `CASE` не изменяет таблицу: новый столбец существует только в результате запроса.

