`JOIN` ставит связанные данные рядом, а `UNION ALL` добавляет результаты запросов друг под другом:

```sql
SELECT 'crew' AS source, message_text AS text, sent_at AS event_time
FROM communications

UNION ALL

SELECT 'ai' AS source, command_text AS text, executed_at AS event_time
FROM ai_commands;
```

Обе части должны возвращать одинаковое число совместимых столбцов. Псевдонимы первой части задают названия итоговых колонок.

