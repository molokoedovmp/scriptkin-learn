JOIN crew_members AS cm
  ON cm.badge_id = al.badge_id
JOIN crew_shifts AS cs
  ON cs.crew_id = cm.crew_id
JOIN sectors AS s
  ON s.sector_id = cs.sector_id
```

Каждый `JOIN` добавляет данные к уже полученному результату. В этой цепочке журнал доступа сначала получает владельца пропуска, затем его смену, а после — понятный код назначенного сектора.

