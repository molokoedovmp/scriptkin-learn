`JOIN` объединяет связанные строки из нескольких таблиц. Условие после `ON` указывает общий ключ:

```sql
FROM cargo_containers AS cc
JOIN cargo_items AS ci
  ON ci.container_id = cc.container_id
```

Здесь `cc` и `ci` — короткие псевдонимы таблиц. С ними проще указывать, из какой таблицы нужно взять колонку:

```sql
cc.container_code
ci.item_code
```

После объединения работает обычный `WHERE`:

```sql
WHERE ci.is_declared = FALSE
  AND ci.hazard_class = 'BIO-4'
```

