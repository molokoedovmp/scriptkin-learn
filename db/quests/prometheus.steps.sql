`NOT EXISTS` оставляет строку, только если связанный подзапрос ничего не нашёл:

```sql
NOT EXISTS (
  SELECT 1
  FROM pod_diagnostics AS pd
  WHERE pd.pod_id = ep.pod_id
    AND pd.status = 'critical'
)
```

Однако такое условие учитывает всю историю аппарата. Для проверки только последнего цикла сначала найди его время коррелированным подзапросом:

```sql
SELECT MAX(pd2.checked_at)
FROM pod_diagnostics AS pd2
WHERE pd2.pod_id = ep.pod_id
```

Затем используй найденное значение внутри `NOT EXISTS`:

```sql
AND NOT EXISTS (
  SELECT 1
  FROM pod_diagnostics AS pd
  WHERE pd.pod_id = ep.pod_id
    AND pd.checked_at = (
      SELECT MAX(pd2.checked_at)
      FROM pod_diagnostics AS pd2
      WHERE pd2.pod_id = ep.pod_id
    )
    AND pd.status = 'critical'
)
```

Подзапрос коррелирован с текущим аппаратом через `ep.pod_id`, поэтому для каждого модуля проверяется собственный последний цикл.
