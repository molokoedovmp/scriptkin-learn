`VALUES` создаёт небольшой временный набор прямо внутри запроса:

```sql
VALUES
  (1, 'INFECTED_SECTORS_ISOLATED'),
  (2, 'REACTOR_SAFETY_DISABLED'),
  (3, 'REACTOR_OVERLOAD_STARTED'),
  (4, 'REPAIR_MODULE_LAUNCHED')
```

Соедини его с журналом через `LEFT JOIN`. Так обязательный шаг останется в результате, даже если соответствующего события нет:

```sql
LEFT JOIN system_events AS se
  ON se.event_type = required.event_type
```

`BOOL_AND` вернёт `TRUE`, только когда событие найдено для каждой строки:

```sql
BOOL_AND(completed_at IS NOT NULL)
```

Последовательность выполненных действий собирается через:

```sql
STRING_AGG(event_type, ' → ' ORDER BY step_order)
```

