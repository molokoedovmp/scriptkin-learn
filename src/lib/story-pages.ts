export function getPublicStoryPage(slug: string) {
  const content = PUBLIC_STORY_PAGES.find((story) => story.slug === slug);
  const quest = getDemoQuest(slug);

  if (!content || !quest || quest.status !== "available") return undefined;
  return { ...content, quest };
}
